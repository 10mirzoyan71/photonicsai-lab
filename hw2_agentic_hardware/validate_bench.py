"""Characterise the simulated bench directly (this is NOT the agent's run): speckle statistics, noise,
enhancement against the number of segments vs theory, and the effect of the background-ring choice.

    python validate_bench.py      # -> figures/validation_*.png, ../report/hw2_bench_validation.tex
"""
import json
import os
import time

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from bench import Bench, focus_search, save_figure  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "figures")
os.makedirs(FIG, exist_ok=True)
b = Bench()
out = {}

# 1. speckle and noise
A = b.macro_matrix(1)
E = A @ (np.random.default_rng(0).random(A.shape[1]) < 0.5).astype(np.complex64)
I = b.kappa * np.abs(E) ** 2
Ic = I.reshape(64, 64) - I.mean()
ac = np.real(np.fft.ifft2(np.abs(np.fft.fft2(Ic)) ** 2)); ac /= ac[0, 0]
prof = ac[0, :8]
s1, s2 = b.detect(E), b.detect(E)
out["speckle"] = {"mean_counts": float(I.mean()), "contrast": float(I.std() / I.mean()),
                  "grain_fwhm_px": float(2 * np.interp(0.5, prof[::-1], np.arange(8)[::-1])),
                  "shot_to_shot_rel_rms": float(np.sqrt(np.mean((s1 - s2) ** 2)) / s1.mean())}
print(out["speckle"], flush=True)

# 2. enhancement vs number of segments (wide ring, 3 px focus)
rows = []
for m, it, fl in [(16, 400, 2), (8, 1500, 4), (4, 6000, 8), (2, 20000, 16), (1, 20000, 32)]:
    t = time.time()
    r = focus_search(b, macropixel=m, focus_size=3, bg_inner=4, bg_outer=30, bg_regions=8, iterations=it, flips=fl, remeasure=True, seed=m)
    d = r["diagnostics"]
    rows.append({"macropixel": m, "N": r["segments"], "iterations": it, "flips": fl, "eta": r["enhancement"], "eta_far": r["enhancement_far"],
                 "noise_free_far": d["enhancement_far_noise_free"], "known_T_far": d["enhancement_oracle_TM_far"],
                 "n_eff": d["n_eff"], "theory": d["enhancement_theory_Neff_over_2pi"], "seconds": time.time() - t})
    print(rows[-1], flush=True)
    if m in (2, 1):
        save_figure(r, os.path.join(FIG, f"validation_m{m}.png"), f"bench validation: macropixel {m} ({r['segments']} segments), {it} iterations")
out["sweep"] = rows

# 3. background ring and focus size (256 segments)
ring = []
for fs, bi, bo in [(3, 6, 14), (3, 4, 30), (1, 4, 30), (5, 4, 30)]:
    r = focus_search(b, macropixel=4, focus_size=fs, bg_inner=bi, bg_outer=bo, bg_regions=8, iterations=6000, flips=8, seed=4)
    ring.append({"focus": fs, "bg_inner": bi, "bg_outer": bo, "eta": r["enhancement"], "eta_far": r["enhancement_far"]})
    print(ring[-1], flush=True)
    if (fs, bi, bo) == (3, 6, 14):
        save_figure(r, os.path.join(FIG, "validation_small_ring.png"), "small background ring (r = 6-14 px): the search also darkens the ring")
out["ring"] = ring
json.dump(out, open(os.path.join(FIG, "validation.json"), "w"), indent=1)

# figure: enhancement vs N
N = np.array([r["N"] for r in rows]); ne = np.array([r["n_eff"] for r in rows])
plt.figure(figsize=(7, 4.2))
nn = np.logspace(1, 3.7, 50)
plt.loglog(N, [r["eta"] for r in rows], "o-", label="search, proximal metric $\\eta$")
plt.loglog(N, [r["eta_far"] for r in rows], "s-", label="search, against far field $\\eta_\\mathrm{far}$")
plt.loglog(N, [r["known_T_far"] for r in rows], "^--", label="binary pattern from the known $T$ (far field)")
plt.loglog(N, ne / (2 * np.pi), "k:", label="theory $N_\\mathrm{eff}/2\\pi$ (Gaussian beam)")
plt.loglog(nn, nn / (2 * np.pi), color="gray", lw=0.8, label="theory $N/2\\pi$ (uniform beam)")
plt.loglog([812], [75], "r*", ms=12, label="Akbulut et al. 2011: 812 segments, 75")
plt.xlabel("number of DMD segments $N$"); plt.ylabel("enhancement"); plt.grid(alpha=0.3, which="both"); plt.legend(fontsize=7)
plt.tight_layout(); plt.savefig(os.path.join(FIG, "validation_vs_N.png"), dpi=160)

# LaTeX
L = ["% generated by hw2_agentic_hardware/validate_bench.py",
     f"\\newcommand{{\\specklecontrast}}{{{out['speckle']['contrast']:.2f}}}",
     f"\\newcommand{{\\specklegrain}}{{{out['speckle']['grain_fwhm_px']:.1f}}}",
     f"\\newcommand{{\\shotnoise}}{{{100 * out['speckle']['shot_to_shot_rel_rms']:.1f}}}",
     "\\newcommand{\\validationtable}{\\begin{tabular}{@{}rrrrrrrrr@{}}\\toprule macropixel & $N$ & $N_\\text{eff}$ & iterations & flips & $\\eta$ & $\\eta_\\text{far}$ & known-$T$ & $N_\\text{eff}/2\\pi$\\\\\\midrule"]
for r in rows:
    L.append(f"{r['macropixel']} & {r['N']} & {r['n_eff']:.0f} & {r['iterations']} & {r['flips']}$\\to$1 & {r['eta']:.1f} & {r['eta_far']:.1f} & {r['known_T_far']:.1f} & {r['theory']:.1f}\\\\")
L.append("\\bottomrule\\end{tabular}}")
L.append("\\newcommand{\\ringtable}{\\begin{tabular}{@{}rcrr@{}}\\toprule focus [px] & ring $r$ [px] & $\\eta$ (proximal) & $\\eta_\\text{far}$\\\\\\midrule")
for r in ring:
    L.append(f"${r['focus']}\\times{r['focus']}$ & {r['bg_inner']}--{r['bg_outer']} & {r['eta']:.1f} & {r['eta_far']:.1f}\\\\")
L.append("\\bottomrule\\end{tabular}}")
open(os.path.join(HERE, "..", "report", "hw2_bench_validation.tex"), "w").write("\n".join(L) + "\n")
print("done")
