"""Writes report/mcp_tools.tex: the tools the camera MCP server exposes, as listed by the server itself (list_tools)."""
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from mcp_bridge import MCPBridge  # noqa: E402
from render_hw3 import tex  # noqa: E402


def arg_list(schema):
    req = set(schema.get("required", []))
    out = []
    for k, v in schema.get("properties", {}).items():
        typ = v.get("type") or "/".join(x.get("type", "object") for x in v.get("anyOf", []) if x.get("type") != "null")
        out.append(f"{k}: {typ or 'object'}" + ("" if k in req else " (opt.)"))
    return ", ".join(out) or "--"


def main():
    br = MCPBridge(tempfile.mkdtemp(prefix="tools_"))
    try:
        L = [r"\begin{longtable}{@{}l p{0.3\linewidth} p{0.45\linewidth}@{}}",
             r"\toprule tool & arguments & what it does\\ \midrule \endhead"]
        for t in br.tool_defs:
            first = " ".join((t.description or "").split()).split(". ")[0].rstrip(".") + "."
            L.append(f"\\texttt{{{tex(t.name)}}} & {tex(arg_list(t.inputSchema))} & {tex(first)}\\\\")
        L += [r"\bottomrule", r"\end{longtable}"]
    finally:
        br.close()
    out = os.path.join(HERE, "..", "report", "mcp_tools.tex")
    open(out, "w", encoding="utf-8").write("% generated by agent/render_tools.py from the server's list_tools\n" + "\n".join(L) + "\n")
    print("wrote", out, f"({len(br.tool_defs)} tools)")


if __name__ == "__main__":
    main()
